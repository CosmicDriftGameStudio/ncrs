//! Localization: translated UI strings with per-string translator context.
//!
//! `strings.json` in the repository root is the source of truth. It holds, per
//! string, the stable key, the English text, the German text and the *context*
//! — where the string appears and what it means. `build.rs` generates the
//! modules included below, so the context cannot drift away from the text.
//!
//! Adding a language means adding its text to `strings.json` and extending the
//! matches in this file. `build.rs` fails the build if a string has no
//! usable context, because a translator works from the JSON file alone.
//!
//! A key ending in `.theme` is a Futurama name. It is not a [`Msg`] but a
//! [`FuturamaName`], and only the Futurama variants of a language
//! (`en-futurama`, `de-futurama`) show it, via [`Language::futurama_name`].
//!
//! Adding a *new string* means adding it to `strings.json` and a variant to
//! [`Msg`]; the compiler then points at every place that needs updating.
use std::fmt;

use ncrs_index_types::{KindCatalog, KindLanguage};

// Everything generated by `build.rs` from `strings.json` lives in one module so
// the generated `match` arms can refer to each other with short paths. A `//!`
// doc comment cannot sit here without a blank line before the item, and clippy
// rejects a blank line between a doc comment and what it documents.
mod gen {
    /// English, the source language.
    pub mod en {
        include!(concat!(env!("OUT_DIR"), "/en.rs"));
    }

    /// German.
    pub mod de {
        include!(concat!(env!("OUT_DIR"), "/de.rs"));
    }

    include!(concat!(env!("OUT_DIR"), "/enum.rs"));
    include!(concat!(env!("OUT_DIR"), "/key.rs"));
    include!(concat!(env!("OUT_DIR"), "/text.rs"));
    include!(concat!(env!("OUT_DIR"), "/lookup.rs"));
    include!(concat!(env!("OUT_DIR"), "/notes.rs"));
    include!(concat!(env!("OUT_DIR"), "/futurama.rs"));
}

/// Every string, for tests that check what a screen shows against all of them.
pub use gen::ALL as ALL_MESSAGES;
pub use gen::{FuturamaName, Msg};

impl Msg {
    /// English text. Every key has one, `build.rs` refuses a blank.
    pub fn text(self) -> &'static str {
        gen::text(self)
    }

    /// Context for translators, generated from the same JSON file as the text.
    ///
    /// Not read at runtime: this exists so a string cannot lose its context
    /// while the translation sheet is generated from the same source.
    pub fn note(self) -> &'static str {
        gen::note(self)
    }

    /// The stable key from strings.json, not the text: a log or the
    /// translation sheet names a string by its key and prints the text next to
    /// it, so printing the localised text here would both duplicate it and put
    /// a translated string into a log.
    pub fn key(self) -> &'static str {
        gen::key(self)
    }
}

impl FuturamaName {
    /// The full key from strings.json, `.theme` included.
    pub fn key(self) -> &'static str {
        gen::futurama_key(self)
    }

    /// Context for translators, like [`Msg::note`].
    pub fn note(self) -> &'static str {
        gen::futurama_note(self)
    }
}

/// The language the UI is currently rendered in. The Futurama variants add
/// the names from the show next to the plain texts of their base language.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
pub enum Language {
    #[default]
    English,
    German,
    EnglishFuturama,
    GermanFuturama,
}

impl Language {
    /// The language without the Futurama names.
    pub fn base(self) -> Self {
        match self {
            Language::English | Language::EnglishFuturama => Language::English,
            Language::German | Language::GermanFuturama => Language::German,
        }
    }

    /// The text in this language. Every key has both texts, `build.rs` refuses a blank one.
    pub fn text(self, msg: Msg) -> &'static str {
        match self.base() {
            Language::German => gen::de_text(msg),
            _ => msg.text(),
        }
    }

    pub fn shows_futurama_names(self) -> bool {
        matches!(self, Language::EnglishFuturama | Language::GermanFuturama)
    }

    /// The same base language, with or without the Futurama names.
    pub fn with_futurama(self, on: bool) -> Self {
        match (self.base(), on) {
            (Language::German, false) => Language::German,
            (Language::German, true) => Language::GermanFuturama,
            (_, false) => Language::English,
            (_, true) => Language::EnglishFuturama,
        }
    }

    /// The Futurama name: only the Futurama variants have one, the standard
    /// languages never show it.
    pub fn futurama_name(self, name: FuturamaName) -> Option<&'static str> {
        self.shows_futurama_names().then(|| match self.base() {
            Language::German => gen::futurama_de(name),
            _ => gen::futurama_en(name),
        })
    }

    /// The plain name, then the theme name in parentheses where there is one.
    pub fn titled(self, label: Msg, theme_name: Option<FuturamaName>) -> String {
        match theme_name.and_then(|name| self.futurama_name(name)) {
            Some(theme) => format!("{} ({})", self.text(label), theme),
            None => self.text(label).to_owned(),
        }
    }

    /// The language the known document kinds are worded in.
    pub fn kind_language(self) -> KindLanguage {
        match self.base() {
            Language::German => KindLanguage::German,
            _ => KindLanguage::English,
        }
    }

    /// A document kind as shown: the word of this language for a known kind,
    /// anything else (user kinds) exactly as stored.
    pub fn kind_label<'a>(
        self,
        kinds: &'a KindCatalog,
        kind: &'a str,
    ) -> std::borrow::Cow<'a, str> {
        kinds.kind_word(kind, self.kind_language())
    }

    /// A tag as shown: a known kind in its word, in tag form.
    pub fn tag_label(self, kinds: &KindCatalog, tag: &str) -> String {
        kinds.kind_tag_word(tag, self.kind_language())
    }

    /// Every language, in the order the config error lists them.
    pub const ALL: [Language; 4] = [
        Language::English,
        Language::German,
        Language::EnglishFuturama,
        Language::GermanFuturama,
    ];

    /// The code written in the config file and shown for the language.
    pub fn code(self) -> &'static str {
        match self {
            Language::English => "en",
            Language::German => "de",
            Language::EnglishFuturama => "en-futurama",
            Language::GermanFuturama => "de-futurama",
        }
    }

    /// The language's name in that language, for the language choice.
    pub fn name(self) -> &'static str {
        match self {
            Language::English => "English",
            Language::German => "Deutsch",
            Language::EnglishFuturama => "English (Futurama)",
            Language::GermanFuturama => "Deutsch (Futurama)",
        }
    }

    pub fn from_code(code: &str) -> Option<Self> {
        Self::ALL.into_iter().find(|lang| lang.code() == code)
    }

    /// The language a system locale tag such as `de_DE.UTF-8`, `de-AT` or
    /// `en_US` asks for, among the two the app has texts for.
    pub fn from_locale_tag(tag: &str) -> Option<Self> {
        let primary = tag
            .trim()
            .split(|ch: char| matches!(ch, '_' | '-' | '.' | '@'))
            .next()
            .unwrap_or_default();
        match primary.to_ascii_lowercase().as_str() {
            "de" => Some(Language::German),
            "en" => Some(Language::English),
            _ => None,
        }
    }

    /// The language of the system for a first start: the first language the
    /// user's locale settings name that the app has texts for, English when
    /// none or when the system cannot be asked.
    pub fn from_system() -> Self {
        let from_environment = ["LC_ALL", "LC_MESSAGES", "LANGUAGE", "LANG"]
            .into_iter()
            .filter_map(|name| std::env::var(name).ok())
            .flat_map(|value| value.split(':').map(str::to_owned).collect::<Vec<_>>())
            .find_map(|tag| Self::from_locale_tag(&tag));
        from_environment
            .or_else(Self::from_macos_preferences)
            .unwrap_or_default()
    }

    /// An app started from the Finder has no locale in its environment; the
    /// preferred languages are in the user defaults.
    fn from_macos_preferences() -> Option<Self> {
        if !cfg!(target_os = "macos") {
            return None;
        }
        let output = std::process::Command::new("defaults")
            .args(["read", "-g", "AppleLanguages"])
            .output()
            .ok()?;
        String::from_utf8_lossy(&output.stdout)
            .lines()
            .map(|line| line.trim().trim_end_matches(',').trim_matches('"'))
            .find_map(Self::from_locale_tag)
    }

    /// Switches between English and German, keeping the Futurama variant, for
    /// the temporary key binding.
    pub fn other(self) -> Self {
        match self {
            Language::English => Language::German,
            Language::German => Language::English,
            Language::EnglishFuturama => Language::GermanFuturama,
            Language::GermanFuturama => Language::EnglishFuturama,
        }
    }
}

impl fmt::Display for Msg {
    /// The stable key, not the text: the translation sheet identifies a string
    /// by its key and prints the text next to it, so printing the text here
    /// would duplicate it and print a localised value into a log.
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "{}", self.key())
    }
}

impl fmt::Display for Language {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(self.code())
    }
}

/// `template` with each placeholder name in `values` replaced by its value.
pub fn fill_template(template: &str, values: &[(&str, &str)]) -> String {
    let mut filled = String::with_capacity(template.len());
    let mut rest = template;
    while !rest.is_empty() {
        let placeholder = values
            .iter()
            .find_map(|(name, value)| rest.strip_prefix(name).map(|after| (value, after)));
        if let Some((value, after)) = placeholder {
            filled.push_str(value);
            rest = after;
        } else {
            let mut chars = rest.chars();
            filled.extend(chars.next());
            rest = chars.as_str();
        }
    }
    filled
}

